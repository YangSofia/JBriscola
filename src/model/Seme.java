
package model;

/**
 * Questa enumerazione definisce un tipo sicuro per i semi, evitando l'uso
 * di stringhe o interi "magici" e migliorando la leggibilità e la manutenibilità
 * del codice.
 */
public enum Seme {
	/** Il seme di Coppe. */
    COPPE,
    
    /** Il seme di Spade. */
    SPADE,
    
    /** Il seme di Denari. */
    DENARI,
    
    /** Il seme di Bastoni. */
    BASTONI
}
